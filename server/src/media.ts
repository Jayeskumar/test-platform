import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { config } from './config.js';
import { getDb, now } from './db/index.js';

/** Proctoring images live on disk (inside the data directory, hidden from the sandbox). */
let mediaRoot = process.env.MEDIA_DIR ?? path.join(config.dataDir, 'media');
export const getMediaRoot = () => mediaRoot;
export function setMediaRoot(dir: string) {
  mediaRoot = dir;
}

export const MAX_IMAGE_BYTES = 450 * 1024;

export function decodeImage(dataUrl: string): { mime: 'image/jpeg' | 'image/png'; buf: Buffer } | null {
  const m = /^data:(image\/(?:jpeg|png));base64,([A-Za-z0-9+/=]+)$/.exec(dataUrl);
  if (!m) return null;
  const buf = Buffer.from(m[2], 'base64');
  const jpeg = buf.length > 3 && buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff;
  const png = buf.length > 8 && buf.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]));
  // The declared type must match the actual bytes.
  if (m[1] === 'image/jpeg' && !jpeg) return null;
  if (m[1] === 'image/png' && !png) return null;
  return { mime: m[1] as 'image/jpeg' | 'image/png', buf };
}

export function storeMedia(attemptId: number, kind: string, img: { mime: string; buf: Buffer }, faces: number | null, reason: string, t: number) {
  const dir = path.join(mediaRoot, String(attemptId));
  fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
  const file = `${kind}-${t}-${crypto.randomBytes(4).toString('hex')}.${img.mime === 'image/png' ? 'png' : 'jpg'}`;
  fs.writeFileSync(path.join(dir, file), img.buf, { mode: 0o600 });
  return getDb().run(
    'INSERT INTO media (attempt_id, kind, t, faces, reason, file, mime, bytes) VALUES (?, ?, ?, ?, ?, ?, ?, ?)',
    attemptId, kind, t, faces, reason, file, img.mime, img.buf.length,
  ).id;
}

export function mediaPath(row: { attempt_id: number; file: string }) {
  // File names are generated by us, but never trust stored paths blindly.
  const name = path.basename(row.file);
  return path.join(mediaRoot, String(row.attempt_id), name);
}

/** Remove all proctoring data for an attempt: images, their rows, and the access log (IPs, devices). */
export function deleteProctoringData(attemptId: number) {
  const db = getDb();
  db.run('DELETE FROM media WHERE attempt_id = ?', attemptId);
  db.run('DELETE FROM access_log WHERE attempt_id = ?', attemptId);
  fs.rmSync(path.join(mediaRoot, String(attemptId)), { recursive: true, force: true });
}

/** Delete proctoring data older than each assessment's retention period. */
export function sweepRetention() {
  const db = getDb();
  const rows = db.all<any>(
    `SELECT a.id, a.submitted_at, s.settings FROM attempts a JOIN assessments s ON s.id = a.assessment_id
     WHERE a.status = 'submitted' AND (EXISTS (SELECT 1 FROM media m WHERE m.attempt_id = a.id) OR EXISTS (SELECT 1 FROM access_log l WHERE l.attempt_id = a.id))`,
  );
  let removed = 0;
  for (const r of rows) {
    let days = 90;
    try { days = Number(JSON.parse(r.settings).retentionDays ?? 90); } catch { /* default */ }
    if (r.submitted_at && r.submitted_at < now() - days * 86400_000) {
      deleteProctoringData(r.id);
      removed++;
    }
  }
  return removed;
}
